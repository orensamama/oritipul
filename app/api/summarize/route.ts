// ─── Handler ──────────────────────────────────────────────────────────────────
export async function POST(req: NextRequest) {
  const apiKey = process.env.OPENAI_API_KEY;

  try {
    const body = await req.json() as {
      text?: string;
      imageBase64?: string;
      mimeType?: string;
      images?: { base64: string; mimeType: string }[];
      style?: string;
      extraNotes?: string;
      knownPatientName?: string;
    };

    // Simulation mode — return mock immediately (no API key)
    if (!apiKey) {
      await new Promise((r) => setTimeout(r, 1500));
      return NextResponse.json(MOCK_SUMMARY);
    }

    const styleNote = body.style === "short"
      ? "כתוב בצורה תמציתית וממוקדת."
      : body.style === "thematic"
      ? "הדגש חלוקה לפי תמות ונושאים."
      : "כתוב בצורה קלינית מורחבת ומפורטת.";

    const extraNotesBlock = body.extraNotes?.trim()
      ? `\n\n═══ הערות/מידע נוסף שסיפקה המטפלת (קול/טקסט/קובץ) ═══\n${body.extraNotes.trim()}\n═══ סוף ההערות הנוספות ═══`
      : "";

    const userContent: object[] = [];

    // Multiple images (multi-page notebook scan)
    if (body.images && Array.isArray(body.images) && body.images.length > 0) {
      const pageWord = body.images.length === 1 ? "דף" : `${body.images.length} דפים`;
      userContent.push({
        type: "text",
        text: `הכתוב בתמונות הבאות הוא טקסט עברי מימין לשמאל — כולל כתב יד. קרא בעיון כל ${pageWord} של מחברת טיפולית וסכם את כולם יחד כמסמך אחד. ${styleNote}${extraNotesBlock}`,
      });
      for (const img of body.images as { base64: string; mimeType: string }[]) {
        userContent.push({
          type: "image_url",
          image_url: {
            url: `data:${img.mimeType ?? "image/jpeg"};base64,${img.base64}`,
            detail: "high",
          },
        });
      }
    // Single legacy image
    } else if (body.imageBase64) {
      userContent.push({
        type: "text",
        text: `הכתוב בתמונה הוא טקסט עברי מימין לשמאל — כולל כתב יד. קרא בעיון את הערות המחברת הטיפולית וסכם לפי ההנחיות. ${styleNote}${extraNotesBlock}`,
      });
      userContent.push({
        type: "image_url",
        image_url: {
          url: `data:${body.mimeType ?? "image/jpeg"};base64,${body.imageBase64}`,
          detail: "high",
        },
      });
    } else {
      userContent.push({
        type: "text",
        text: `סכם את הפגישה הטיפולית הבאה. ${styleNote}\n\n═══ תמלול מלא של הפגישה ═══\n${body.text}\n═══ סוף התמלול ═══${extraNotesBlock}`,
      });
    }

    const res = await fetch("https://api.openai.com/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${apiKey}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "gpt-4o",
        messages: [
          { role: "system", content: SYSTEM_PROMPT },
          { role: "user",   content: userContent },
        ],
        response_format: { type: "json_object" },
        temperature: 0.2,
        max_tokens: 2000,
      }),
    });

    if (!res.ok) {
      const errText = await res.text();
      return NextResponse.json({ error: errText }, { status: res.status });
    }

    const data = await res.json();
    const parsed = JSON.parse(data.choices[0].message.content);
    // Server-side anonymization backstop: never trust the prompt alone. Runs
    // only on OpenAI's response — knownPatientName is never sent to OpenAI.
    return NextResponse.json(sanitizeJsonStrings(parsed, [body.knownPatientName]));
  } catch (err) {
    return NextResponse.json({ error: String(err) }, { status: 500 });
  }
}
